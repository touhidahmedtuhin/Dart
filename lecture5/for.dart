void main() {
  //For loop
  for (int i = 1; i <= 5; i++) {
    print("Number: $i");
  }

  //For loop in List
  var names = ["Touhid", "Rahim", "Karim"];

  for (int i = 0; i < names.length; i++) {
    print("Name: ${names[i]}");
  }

  //Reverse Loop

  for (int i = 5; i >= 1; i--) {
    print("Countdown: $i");
  }

}
